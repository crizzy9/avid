export type AppMessageKey = keyof typeof appMessages;
/** Exact originals let App integration replace literals without matching book content. */
export const appMessageKeysByEnglish: Readonly<Record<string, AppMessageKey>> =
  Object.freeze(
    Object.fromEntries(
      Object.entries(appMessages).map(([key, translations]) => [
        translations[0],
        key as AppMessageKey,
      ]),
    ),
  );
export function appTranslate(
  key: AppMessageKey,
  parameters: Parameters = {},
  locale: Locale = getLocale(),
): string {
  const index = LOCALES.findIndex((item) => item.code === locale);
  return appMessages[key][index < 0 ? 0 : index]!.replace(
    /\{(\w+)\}/g,
    (token, name: string) => {
      const value = parameters[name];
      return value === undefined
        ? token
        : typeof value === "number"
          ? new Intl.NumberFormat(locale).format(value)
          : value;
    },
  );
}
export function useAppI18n() {
  const { locale } = useI18n();
  return {
    locale,
    t: (key: AppMessageKey, parameters?: Parameters) =>
      appTranslate(key, parameters),
  };
}
