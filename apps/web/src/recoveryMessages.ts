export type RecoveryMessageKey = keyof typeof recoveryMessages;
export function recoveryTranslate(
  key: RecoveryMessageKey,
  parameters: Record<string, string | number> = {},
  locale: Locale = getLocale(),
) {
  const index = LOCALES.findIndex((item) => item.code === locale);
  return recoveryMessages[key][index < 0 ? 0 : index].replace(
    /\{(\w+)\}/g,
    (token, name: string) =>
      parameters[name] === undefined ? token : String(parameters[name]),
  );
}
export function useRecoveryI18n() {
  const { locale } = useI18n();
  return { locale, t: recoveryTranslate };
}
