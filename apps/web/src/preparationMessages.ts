export type PreparationMessage = keyof typeof preparationMessages;
export function preparationT(
  key: PreparationMessage,
  values: Record<string, string | number> = {},
  locale: Locale = getLocale(),
): string {
  const index = LOCALES.findIndex((item) => item.code === locale);
  return preparationMessages[key][index < 0 ? 0 : index].replace(
    /\{(\w+)\}/g,
    (token, name: string) =>
      values[name] === undefined ? token : String(values[name]),
  );
}
export function usePreparationI18n() {
  const { locale } = useI18n();
  return (
    key: PreparationMessage,
    values: Record<string, string | number> = {},
  ) => preparationT(key, values, locale);
}
