export type HomePinMessageKey = keyof typeof homePinMessages;
export function homePinT(
  key: HomePinMessageKey,
  values: Record<string, string | number> = {},
  locale: Locale = getLocale(),
): string {
  const index = LOCALES.findIndex((item) => item.code === locale);
  return homePinMessages[key][index < 0 ? 0 : index].replace(
    /\{(\w+)\}/g,
    (token, name: string) =>
      values[name] === undefined ? token : String(values[name]),
  );
}
