export type PlaybackSettingsMessage = keyof typeof playbackSettingsMessages;
export function playbackSettingsTranslate(
  key: PlaybackSettingsMessage,
  parameters: Record<string, string | number> = {},
  locale: Locale = "en",
): string {
  return playbackSettingsMessages[key][
    LOCALES.findIndex((item) => item.code === locale)
  ].replace(/\{(\w+)\}/g, (token, name: string) =>
    String(parameters[name] ?? token),
  );
}
export function usePlaybackSettingsI18n() {
  const { locale } = useI18n();
  return (
    key: PlaybackSettingsMessage,
    parameters?: Record<string, string | number>,
  ) => playbackSettingsTranslate(key, parameters, locale);
}
