export function connectorTranslate(
  key: ConnectorMessageKey,
  values: Record<string, string | number> = {},
  locale: Locale = getLocale(),
) {
  const index = LOCALES.findIndex((item) => item.code === locale);
  return connectorMessages[key][index < 0 ? 0 : index].replace(
    /\{(\w+)\}/g,
    (token, name: string) =>
      values[name] === undefined
        ? token
        : typeof values[name] === "number"
          ? new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(
              values[name],
            )
          : values[name],
  );
}
export function useConnectorI18n() {
  const { locale } = useI18n();
  return { locale, t: connectorTranslate };
}
const deviceErrors: Record<CrossPointErrorCode, ConnectorMessageKey> = {
  "invalid-address": "invalidAddress",
  "invalid-path": "invalidPath",
  "unsupported-file": "unsupportedFile",
  unreachable: "unreachable",
  "unexpected-response": "unexpectedResponse",
  "file-exists": "fileExists",
  "device-changed": "deviceChanged",
  "upload-uncertain": "uploadUncertain",
  "invalid-plan": "invalidPlan",
  busy: "deviceBusy",
};
/** Known application failures are translated; account names and publication text are never rewritten. */
export function connectorError(
  error: unknown,
  service: "ao3" | "crosspoint",
): ConnectorNotice {
  if (
    typeof error === "object" &&
    error !== null &&
    "name" in error &&
    error.name === "AbortError"
  )
    return { key: "cancelled" };
  if (error instanceof CrossPointError)
    return { key: deviceErrors[error.code] };
  if (error instanceof Ao3Error) {
    if (error.status === 401) return { key: "ao3Auth" };
    if (error.status === 403) return { key: "ao3Restricted" };
    if (error.status === 429 || error.status === 503)
      return {
        key: "retryLater",
        values: { seconds: Math.max(1, Math.ceil(error.retryAfter ?? 60)) },
      };
    if (
      error.message.startsWith("Use a local HTTP companion") ||
      error.message.startsWith("Use the local companion address")
    )
      return { key: "ao3AddressError" };
    if (error.message.startsWith("Enter the pairing code"))
      return { key: "ao3PairingError" };
    if (error.message.startsWith("This work changed during download"))
      return { key: "workChanged" };
    return { key: "ao3Response" };
  }
  return { key: service === "ao3" ? "ao3Failure" : "deviceFailure" };
}
