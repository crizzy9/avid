import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const messages = JSON.parse(
  readFileSync(`${root}packages/i18n/native-messages.json`, "utf8"),
);
const locales = ["en", "fi", "fr", "de", "pl", "zh-Hans", "es"];
const placeholders = (text) =>
  [...text.matchAll(/\$?\{[^}]+\}/g)]
    .map((m) => m[0])
    .sort()
    .join("|");
for (const [key, values] of Object.entries(messages)) {
  if (
    values.length !== 6 ||
    values.some(
      (value) =>
        typeof value !== "string" ||
        !value.trim() ||
        placeholders(value) !== placeholders(key),
    )
  )
    throw Error(`Invalid translation: ${key}`);
}
const write = (file, text) => {
  mkdirSync(dirname(`${root}${file}`), { recursive: true });
  writeFileSync(`${root}${file}`, text);
};
for (const [index, locale] of locales.entries()) {
  for (const [name, shortcuts] of [
    ["Localizable", false],
    ["AppShortcuts", true],
  ]) {
    const entries = Object.entries(messages).filter(
      ([key]) => key.includes("${applicationName}") === shortcuts,
    );
    write(
      `apps/mobile/native/ios/Shared/Locales/${locale}.lproj/${name}.strings`,
      "// Generated by scripts/generate-native-messages.mjs.\n" +
        entries
          .map(
            ([key, values]) =>
              `${JSON.stringify(key)} = ${JSON.stringify(index ? values[index - 1] : key)};`,
          )
          .join("\n") +
        "\n",
    );
  }
}
const kotlin = (text) => JSON.stringify(text).replaceAll("$", "\\$");
const xml = (text) =>
  text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"');
for (const [index, locale] of locales.entries()) {
  const text = (key) => (index ? messages[key][index - 1] : key);
  const entries = {
    avid_widget_name: text("Continue with Avid"),
    avid_widget_description: text("Resume your latest book in Avid."),
    avid_widget_heading: `Avid · ${text("Continue reading")}`,
    avid_widget_empty_title: text("Your next chapter awaits."),
    avid_widget_empty_detail: text("Open a book in Avid to continue here."),
    avid_widget_progress: text("{percent}% complete")
      .replaceAll("%", "%%")
      .replace("{percent}", "%1$d"),
  };
  const folder =
    locale === "en"
      ? "values"
      : locale === "zh-Hans"
        ? "values-b+zh+Hans"
        : `values-${locale}`;
  write(
    `apps/mobile/android/app/src/main/res/${folder}/avid_native_messages.xml`,
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-native-messages.mjs. -->\n<resources>\n' +
      Object.entries(entries)
        .map(
          ([key, value]) => `    <string name="${key}">${xml(value)}</string>`,
        )
        .join("\n") +
      "\n</resources>\n",
  );
}
write(
  "apps/mobile/native/android/src/main/java/app/avid/playback/AvidStrings.kt",
  `// Generated by scripts/generate-native-messages.mjs.
package app.avid.playback

import android.content.Context

object AvidStrings {
    private val locales = listOf(${locales.map(kotlin).join(", ")})
    private val messages = mapOf(
${Object.entries(messages)
  .filter(([key]) => !key.includes("${applicationName}"))
  .map(
    ([key, values]) =>
      `        ${kotlin(key)} to listOf(${values.map(kotlin).join(", ")})`,
  )
  .join(",\n")}
    )
    fun valid(locale: String) = locale in locales
    fun text(context: Context, key: String): String {
        val locale = context.getSharedPreferences("avid-appearance", Context.MODE_PRIVATE).getString("locale", "en") ?: "en"
        val index = locales.indexOf(locale) - 1
        return if (index >= 0) messages[key]?.getOrNull(index) ?: key else key
    }
}
`,
);
console.log(
  `Generated ${Object.keys(messages).length} native messages for ${locales.length} locales.`,
);
